/**
 * core/db/schema/auth.ts — the identity tables owned by Better Auth (ADR-0006).
 *
 * Why these are OUR tables: ADR-0006 put users and sessions inside our own
 * Postgres so that every pg_dump contains them. A restore then brings back
 * accounts AND their data together; nothing is orphaned.
 *
 * Where the shape comes from: generated with the official Better Auth CLI
 * (`npx @better-auth/cli generate`) for this exact configuration
 * (core/auth/auth.ts: email+password, uuid ids, database rate limiting), then
 * edited in two ways:
 *   - timestamps use `withTimezone: true` (ADR-0003: store UTC with time zone);
 *   - comments added.
 * If you change Better Auth options or upgrade it, re-run the CLI into a temp
 * file and diff it against this one: Better Auth reads/writes these columns by
 * their TypeScript property names (userId, expiresAt, ...), so names matter.
 *
 * Linked files: core/auth/auth.ts passes these tables to Better Auth's Drizzle
 * adapter; every user-owned table in nutrition.ts references `user.id`.
 */
import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  index,
  integer,
  pgTable,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";

/** Shorthand used by every table: timestamp with time zone. */
const tstz = (name: string) => timestamp(name, { withTimezone: true });

/** Primary key generated by Postgres (ADR-0003: database-generated UUIDs). */
const idColumn = () =>
  uuid("id")
    .default(sql`pg_catalog.gen_random_uuid()`)
    .primaryKey();

/** One row per person. `email` is the login name. */
export const user = pgTable("user", {
  id: idColumn(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").default(false).notNull(),
  image: text("image"),
  createdAt: tstz("created_at").defaultNow().notNull(),
  // $onUpdate runs in Drizzle (JS side) whenever a row is updated through it.
  updatedAt: tstz("updated_at")
    .defaultNow()
    .$onUpdate(() => new Date())
    .notNull(),
});

/**
 * One row per logged-in device/browser. The cookie holds `token`; deleting the
 * row logs that device out (ADR-0006: "sessions are rows, so revoking one is a
 * delete"). `onDelete: cascade`: deleting a user deletes their sessions.
 */
export const session = pgTable(
  "session",
  {
    id: idColumn(),
    expiresAt: tstz("expires_at").notNull(),
    token: text("token").notNull().unique(),
    createdAt: tstz("created_at").defaultNow().notNull(),
    updatedAt: tstz("updated_at")
      .$onUpdate(() => new Date())
      .notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
  },
  (table) => [index("session_userId_idx").on(table.userId)],
);

/**
 * Credentials. For email+password, providerId is "credential" and `password`
 * holds the HASH (Better Auth hashes it; the plain password is never stored).
 * The OAuth columns stay empty until a social login is ever added.
 */
export const account = pgTable(
  "account",
  {
    id: idColumn(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: uuid("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: tstz("access_token_expires_at"),
    refreshTokenExpiresAt: tstz("refresh_token_expires_at"),
    scope: text("scope"),
    password: text("password"),
    createdAt: tstz("created_at").defaultNow().notNull(),
    updatedAt: tstz("updated_at")
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("account_userId_idx").on(table.userId)],
);

/** Short-lived tokens (email verification, password reset). Unused in v1. */
export const verification = pgTable(
  "verification",
  {
    id: idColumn(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: tstz("expires_at").notNull(),
    createdAt: tstz("created_at").defaultNow().notNull(),
    updatedAt: tstz("updated_at")
      .defaultNow()
      .$onUpdate(() => new Date())
      .notNull(),
  },
  (table) => [index("verification_identifier_idx").on(table.identifier)],
);

/**
 * Login attempt counters. Why in the database: on Vercel every request may run
 * in a different short-lived function instance, so an in-memory counter would
 * reset constantly and never actually limit password guessing.
 */
export const rateLimit = pgTable("rate_limit", {
  id: idColumn(),
  key: text("key").notNull().unique(),
  count: integer("count").notNull(),
  lastRequest: bigint("last_request", { mode: "number" }).notNull(),
});
