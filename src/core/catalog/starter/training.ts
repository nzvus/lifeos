import type { PackInput } from "../pack";

type P = Required<Pick<PackInput, "exercises" | "routines" | "programs">>;
type Exercise = P["exercises"][number];

const s = (
  name: string,
  muscleGroups: string[],
  pattern: string | null,
  equipment: string | null,
  notes: string,
  unilateral = false,
): Exercise => ({
  name,
  kind: "strength",
  muscleGroups,
  pattern,
  equipment,
  notes,
  unilateral,
});
const bw = (...a: Parameters<typeof s>): Exercise => ({ ...s(...a), kind: "bodyweight" });
const cardio = (
  name: string,
  pattern: string,
  notes: string,
  groups: string[] = [],
): Exercise => ({
  name,
  kind: "cardio",
  muscleGroups: groups,
  pattern,
  equipment: null,
  notes,
});

